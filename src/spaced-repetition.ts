export interface SpacedRepetitionCard {
  question?: string;
  answer?: string;
}

/**
 * Normalize a deck name into the tag hierarchy used by Obsidian Spaced Repetition.
 * Input may be `topic/subtopic`, `flashcards/topic`, or `#flashcards/topic`.
 */
export function normalizeSpacedRepetitionDeckTag(value: string): string {
  let raw = String(value ?? "").trim().replace(/^#+\s*/, "");
  raw = raw.replace(/^flashcards(?:\/|$)/i, "");
  const segments = raw.split("/").map(part => part.trim())
    .map(part => part.replace(/[^\p{L}\p{N}_-]+/gu, "-").replace(/^-+|-+$/g, ""))
    .filter(Boolean);
  return ["flashcards", ...segments].join("/");
}

/** Keep output within the Vault and reject traversal/absolute paths. */
export function normalizeSpacedRepetitionFolderPath(value: string): string {
  const raw = String(value ?? "").trim().replace(/\\/g, "/").replace(/\/+$/g, "");
  if (!raw) throw new Error("复习卡组目录不能为空。");
  if (raw.startsWith("/") || /^[a-zA-Z]:/.test(raw)) {
    throw new Error("复习卡组目录必须是 Vault 内的相对路径。");
  }
  const parts = raw.split("/");
  if (parts.some(part => !part.trim() || part.trim() === "." || part.trim() === "..")) {
    throw new Error("复习卡组目录不能包含空路径段或 . / .. 路径段。");
  }
  const clean = parts.map(part => part.trim().replace(/[<>:"|?*\u0000-\u001f]/g, "-").replace(/[. ]+$/g, ""));
  if (clean.some(part => !part)) throw new Error("复习卡组目录中包含无效的目录名称。");
  return clean.join("/");
}

export function sanitizeSpacedRepetitionTitle(value: string): string {
  const firstLine = String(value ?? "").replace(/\r\n?/g, "\n").split("\n", 1)[0]
    .replace(/^\s*#+\s*/, "").trim();
  const clean = firstLine.replace(/[\\/:*?"<>|\u0000-\u001f]/g, "-")
    .replace(/^\.+/, "").replace(/\s+/g, " ").replace(/[. ]+$/g, "").slice(0, 80).trim();
  return clean && !/^[-_]+$/.test(clean) ? clean : "Flashcards";
}

/** Return a non-overwriting Markdown path, suffixing the basename on collision. */
export function uniqueSpacedRepetitionPath(
  folderPath: string,
  sourceTitle: string,
  existingPaths: Iterable<string>
): string {
  const folder = normalizeSpacedRepetitionFolderPath(folderPath);
  const base = sanitizeSpacedRepetitionTitle(sourceTitle);
  const occupied = new Set(Array.from(existingPaths, path => String(path).toLocaleLowerCase()));
  let candidate = folder + "/" + base + ".md";
  let suffix = 2;
  while (occupied.has(candidate.toLocaleLowerCase())) {
    candidate = folder + "/" + base + " " + suffix++ + ".md";
  }
  return candidate;
}

function normalizeCardSide(value: string): string {
  return String(value ?? "").replace(/\r\n?/g, "\n").trim()
    // A standalone question mark is the Spaced Repetition multi-line separator.
    .replace(/^[ \t]*\?[ \t]*$/gm, "？");
}

/**
 * Build a Markdown note recognized by the Obsidian Spaced Repetition plugin.
 * Uses the plugin's multi-line Q/A syntax, preserving answer Markdown.
 */
export function formatSpacedRepetitionDeck(
  cards: ReadonlyArray<SpacedRepetitionCard>,
  deckName: string,
  noteTitle: string
): string {
  const valid = cards.map(card => ({
    question: typeof card.question === "string" ? normalizeCardSide(card.question) : "",
    answer: typeof card.answer === "string" ? normalizeCardSide(card.answer) : ""
  })).filter(card => card.question && card.answer).slice(0, 100);
  if (!valid.length) throw new Error("没有可导出的有效闪卡。");

  const tag = normalizeSpacedRepetitionDeckTag(deckName);
  const title = sanitizeSpacedRepetitionTitle(noteTitle);
  const body = valid.map(card => card.question + "\n?\n" + card.answer).join("\n\n");
  return [
    "---",
    "tags:",
    "  - " + tag,
    "---",
    "",
    "# " + title,
    "",
    "<!-- Generated by Better Canvas. Re-exporting creates a new file to avoid overwriting existing notes. -->",
    "",
    body,
    ""
  ].join("\n");
}
